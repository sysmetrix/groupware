// Builds the in-browser bundle and a one-click bookmarklet.
// Usage: node scripts/live-build.mjs [--copy-to <dir>]
//   build/live/gw-live.js        collector + briefing renderer (for Aside / DevTools snippet)
//   build/live/bookmarklet.txt   javascript: URL (drag from install.html)
//   build/live/install.html      page with the draggable bookmarklet link
import fs from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const outDir = path.join(root, 'build', 'live');
const collector = await fs.readFile(path.join(root, 'src', 'live', 'collector.browser.js'), 'utf8');
const briefingSrc = await fs.readFile(path.join(root, 'src', 'live', 'briefing.mjs'), 'utf8');
if (/^\s*import\s/m.test(briefingSrc)) throw new Error('briefing.mjs must stay dependency-free to be bundled.');
const briefing = briefingSrc.replace(/^export\s+(?=(async\s+)?function|const|let|class)/gm, '');

const runner = `
(() => {
  const KEY = 'bwyfgw:state';
  const open = () => window.open('', '_blank');
  window.BWYFGW_RUN = async function run(options = {}) {
    const win = options.window === false ? null : open();
    if (win) win.document.write('<meta charset="utf-8"><title>그룹웨어 브리핑</title><p style="font:15px sans-serif;padding:24px">그룹웨어 자료를 읽는 중입니다… (읽기 전용)</p>');
    try {
      const raw = await window.BWYFGW.collect(options);
      let prev = null; try { prev = JSON.parse(localStorage.getItem(KEY) || 'null'); } catch {}
      const analysis = BWYFGW_REPORT.analyze(raw, prev && Date.parse(prev.at) < Date.parse(raw.collectedAt) ? prev : null);
      if (!raw.sessionExpired) localStorage.setItem(KEY, JSON.stringify(BWYFGW_REPORT.nextState(raw, prev)));
      const html = BWYFGW_REPORT.renderHtml(analysis);
      if (win) { win.document.open(); win.document.write(html); win.document.close(); }
      if (options.download) {
        const a = document.createElement('a');
        a.href = URL.createObjectURL(new Blob([JSON.stringify(raw)], {type: 'application/json'}));
        a.download = 'gw-raw-' + raw.collectedAt.slice(0, 10) + '.json'; a.click();
      }
      return {raw, analysis};
    } catch (e) {
      const msg = (e && e.message) || String(e);
      if (win) win.document.body.innerHTML = '<p style="font:15px sans-serif;padding:24px;color:#c00">실행하지 못했습니다: ' + msg.replace(/</g, '&lt;') + '</p>';
      throw e;
    }
  };
})();`;

const bundle = `/* BWYF groupware live bundle — generated by scripts/live-build.mjs on ${new Date().toISOString()} */\n${collector}\n(() => {\n${briefing}\nwindow.BWYFGW_REPORT = Object.freeze({analyze, nextState, renderHtml, renderMarkdown, extractDeadline});\n})();\n${runner}\n`;
await fs.mkdir(outDir, {recursive: true});
await fs.writeFile(path.join(outDir, 'gw-live.js'), bundle);

// Bookmarklet: load the bundle once per page, then run.
const minimal = bundle.replace(/^\s*\/\/.*$/gm, '').replace(/\n\s+/g, '\n');
const bookmarklet = 'javascript:' + encodeURIComponent(`(function(){if(location.origin!=='https://gw.bwyf.or.kr'){alert('그룹웨어(gw.bwyf.or.kr) 화면에서 눌러 주세요.');return;}if(!window.BWYFGW_RUN){${minimal}}window.BWYFGW_RUN({download:false}).catch(function(e){alert('그룹웨어 브리핑 실패: '+(e&&e.message||e));});})();`);
await fs.writeFile(path.join(outDir, 'bookmarklet.txt'), bookmarklet);
const install = `<!doctype html><html lang="ko"><head><meta charset="utf-8"><title>그룹웨어 원클릭 브리핑 설치</title><style>body{font:15px/1.6 "Malgun Gothic",sans-serif;max-width:720px;margin:40px auto;padding:0 18px}a.bm{display:inline-block;padding:10px 18px;border-radius:8px;background:#1a73e8;color:#fff;text-decoration:none;font-weight:700}code{background:#f1f3f4;padding:1px 5px;border-radius:4px}</style></head><body>
<h1>그룹웨어 원클릭 브리핑</h1>
<p>아래 파란 버튼을 브라우저 <b>북마크바로 끌어다 놓으세요</b>. 그룹웨어(gw.bwyf.or.kr)에 로그인한 화면에서 북마크를 누르면 새 탭에 브리핑이 열립니다.</p>
<p><a class="bm" href="${bookmarklet.replace(/"/g, '&quot;')}">GW 브리핑</a></p>
<ul><li>읽기 전용입니다. 메일·문서·게시글을 열지 않아 읽음 상태가 바뀌지 않습니다.</li><li>결재·메일·공지·일정·근태·연차·예산(A201 · 노121)을 0.3초 안팎으로 읽습니다.</li><li>지난 실행과 비교한 "새 항목" 표시는 이 브라우저의 그룹웨어 저장소(localStorage)에 ID만 보관합니다.</li><li>북마크 크기: ${Math.round(bookmarklet.length / 1024)}KB · 생성 ${new Date().toISOString().slice(0, 10)}</li></ul>
</body></html>`;
await fs.writeFile(path.join(outDir, 'install.html'), install);

const copyIdx = process.argv.indexOf('--copy-to');
if (copyIdx > 0 && process.argv[copyIdx + 1]) {
  const dest = process.argv[copyIdx + 1];
  await fs.mkdir(dest, {recursive: true});
  await fs.copyFile(path.join(outDir, 'gw-live.js'), path.join(dest, 'gw-live.js'));
}
console.log(JSON.stringify({bundle: path.join(outDir, 'gw-live.js'), bundleKB: Math.round(bundle.length / 1024), bookmarkletKB: Math.round(bookmarklet.length / 1024), install: path.join(outDir, 'install.html')}));
